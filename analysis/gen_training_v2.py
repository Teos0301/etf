BODY_FONT = '仿宋'
HEAD_FONT = '黑体'

def set_run(run, text, size=12, bold=False, font=BODY_FONT):
    run.text = text
    run.font.name = 'Times New Roman'
    run.font.size = Pt(size)
    run.font.bold = bold
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    rFonts.set(qn('w:eastAsia'), font)

def para(doc, text='', size=12, bold=False, font=BODY_FONT, align=None, indent=True, space_after=6):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Pt(size * 2)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.4
    if align:
        p.alignment = align
    set_run(p.add_run(), text, size, bold, font)
    return p

def h1(doc, text):
    return para(doc, text, 16, True, HEAD_FONT, indent=False, space_after=10)

def h2(doc, text):
    return para(doc, text, 14, True, HEAD_FONT, indent=False, space_after=8)

def h3(doc, text):
    return para(doc, text, 12, True, HEAD_FONT, indent=False, space_after=6)

def shade(cell, hexcolor='D9E2F3'):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:fill'), hexcolor)
    tcPr.append(shd)

def table(doc, headers, rows, widths=None, size=10.5):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ''
        p = c.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_run(p.add_run(), h, size, True, HEAD_FONT)
        shade(c)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ''
            p = cells[i].paragraphs[0]
            set_run(p.add_run(), str(v), size, False, BODY_FONT)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

